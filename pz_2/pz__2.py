# Дни недели: 0 — воскресенье, 1 — понедельник, ..., 6 — суббота
days = ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"]
try:
    k = int(input("Введите номер дня года (от 1 до 365): "))
    if 1 <= k <= 365:
        day_of_week = k % 7
        print(f"День недели: {days[day_of_week]}")
    else:
        print("Ошибка: число должно быть в диапазоне от 1 до 365.")
except ValueError:
    print("Ошибка: нужно ввести целое число")
