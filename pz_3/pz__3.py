# Проверить истинность высказывания: "Точка с координатами (x, y) лежит внутри
# прямоугольника, левая верхняя вершина которого имеет координаты (x1, y1),
# правая нижняя — (x2, y2), а стороны параллельны координатным осям"
try:
    x  = float(input("Введите x:"))
    y  = float(input("Введите y:"))
    x1 = float(input("Введите x1:"))
    y1 = float(input("Введите y1:"))
    x2 = float(input("Введите x2:"))
    y2 = float(input("Введите y2:"))

    if x1 < x < x2 and y2 < y < y1:
        print("Истинно: точка лежит внутри прямоугольника")
    else:
        print("Ложно: точка не лежит внутри прямоугольника")

except ValueError:
    print("Ошибка!Введите числа")


